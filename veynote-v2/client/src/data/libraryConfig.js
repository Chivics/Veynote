export function statusColorClass(status) {
  const c = STATUS_COLORS[status] || "gray";
  const map = {
    red: "bg-danger/15 text-danger",
    blue: "bg-[#5fa8ff]/15 text-[#7db9ff]",
    green: "bg-success/15 text-success",
    gray: "bg-app-panel2 text-ink-muted border border-app-border",
  };
  return map[c];
}
